"""Read the supplied DIVIPOLA workbook without modifying it. Usage: python import-divipola.py file.xlsx"""
import collections
import hashlib
import json
import pathlib
import sys
import openpyxl

source = pathlib.Path(sys.argv[1])
rows = list(openpyxl.load_workbook(source, read_only=True, data_only=True).active.values)
assert rows[0][:4] == ('Código Departamento', 'Nombre Departamento', 'Código Municipio', 'Nombre Municipio')
departments = {}
municipalities = []
for department, department_name, code, name, kind, *_ in rows[1:]:
    assert isinstance(department, str) and len(department) == 2 and department.isdigit()
    assert isinstance(code, str) and len(code) == 5 and code.startswith(department) and code.isdigit()
    assert department not in departments or departments[department] == department_name
    departments[department] = department_name
    municipalities.append([code, name, kind])
assert len({row[0] for row in municipalities}) == len(municipalities)
data = {
    'source': {'file': source.name, 'sha256': hashlib.sha256(source.read_bytes()).hexdigest(), 'sheet': 'Data'},
    'departments': sorted(departments.items()),
    'municipalities': municipalities,
}
target = pathlib.Path(__file__).resolve().parents[1] / 'web' / 'colombia-divipola-data.js'
target.write_text('// Generated by scripts/import-divipola.py from the supplied workbook. Preserve codes as text.\nexport const divipola = ' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(json.dumps({'departments': len(departments), 'locations': len(municipalities), 'types': dict(collections.Counter(row[2] for row in municipalities))}))
