import {professionalView,normalizeProfessional} from '../web/professional-model.js';
import {allyCategories,validSpecialty} from '../web/ally-categories.js';
const readJson=async(bucket,key)=>{const object=await bucket.get(key);return object?{value:await object.json(),etag:object.etag}:null;};
const metadata={httpMetadata:{contentType:'application/json'}};
export function profileView(profile){
  if(!profile)return null;
  const {id,kind,name,headline,category,specialty,shareInProjects,revision}=profile;
  return {...professionalView(profile),id,kind,name,headline,category:category||'',specialty:specialty||'',shareInProjects,revision,avatarUrl:profile.avatarKey?'/api/profile/avatar?v='+revision:null};
}
export function participantsView(record,base){
  return {...record,participants:(record.participants||[]).map(({id,name,kind,headline,role})=>({id,name,kind,headline,role,avatarUrl:base+'/participants/'+id+'/avatar'}))};
}
export async function attachProfile(record,bucket,prefix,role){
  if(record.kind!=='proyecto')return false;
  const profileKey=prefix+'profile.json',stored=await readJson(bucket,profileKey),p=stored?.value;
  if(!p?.shareInProjects)return false;
  const participant={id:p.id,name:p.name,kind:p.kind,headline:p.headline||p.specialty||p.category||'',role,profileKey};
  const participants=record.participants||[],index=participants.findIndex(x=>x.id===p.id);
  if(index>=0)participants[index]=participant;
  else if(participants.length<100)participants.push(participant);
  else return false;
  record.participants=participants;return true;
}
// Only a bounded PNG generated by the profile editor is accepted. SVG and remote URLs are excluded.
export function decodeAvatar(value){
  if(typeof value!=='string'||value.length>100000||!/^data:image\/png;base64,[A-Za-z0-9+/]+={0,2}$/.test(value))throw Error('Usa una imagen PNG de 128 × 128 píxeles.');
  const bytes=Uint8Array.from(atob(value.split(',')[1]),c=>c.charCodeAt(0)),view=new DataView(bytes.buffer);
  if(bytes.length<45||bytes.length>70000||[137,80,78,71,13,10,26,10].some((b,i)=>bytes[i]!==b)||view.getUint32(8)!==13||String.fromCharCode(...bytes.slice(12,16))!=='IHDR'||view.getUint32(16)!==128||view.getUint32(20)!==128||bytes[24]!==8||![2,6].includes(bytes[25])||bytes[26]!==0||bytes[27]!==0||bytes[28]!==0)throw Error('La imagen debe medir 128 × 128 píxeles.');
  let at=8,idat=false,ended=false;
  while(at+12<=bytes.length){const length=view.getUint32(at),type=String.fromCharCode(...bytes.slice(at+4,at+8));if(at+length+12>bytes.length)throw Error('La imagen PNG está incompleta.');if(type==='IDAT')idat=true;at+=length+12;if(type==='IEND'){ended=length===0&&at===bytes.length;break;}}
  if(!idat||!ended)throw Error('La imagen PNG está incompleta.');
  return bytes;
}
export async function profilesApi(request,env,context){
  const {bucket,prefix,json,error,bodyBytes,text,uuid}=context,url=new URL(request.url),path=url.pathname;
  async function image(profileKey,fallback=false){
    const p=(await readJson(bucket,profileKey))?.value;
    const image=p?.avatarKey?await bucket.get(p.avatarKey):null;
    if(!image){
      if(!fallback||!p)error(404,'Este perfil no tiene imagen.');
      const initials=p.name.trim().split(/\s+/).slice(0,2).map(w=>Array.from(w)[0]).join('').toLocaleUpperCase('es').replace(/[&<>"']/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
      return new Response(`<svg xmlns="http://www.w3.org/2000/svg" width="128" height="128" viewBox="0 0 128 128"><rect width="128" height="128" rx="64" fill="${p.kind==='company'?'#dcefe9':'#e3edff'}"/><text x="64" y="65" dominant-baseline="central" text-anchor="middle" fill="${p.kind==='company'?'#17624f':'#164caa'}" font-family="Arial,sans-serif" font-size="38" font-weight="700">${initials}</text></svg>`,{headers:{'content-type':'image/svg+xml','cache-control':'private, no-store','x-content-type-options':'nosniff'}});
    }
    return new Response(image.body,{headers:{'content-type':'image/png','cache-control':'private, no-store','x-content-type-options':'nosniff'}});
  }
  if(path==='/api/profile/avatar'&&request.method==='GET')return image(prefix+'profile.json');
  const participant=path.match(/^\/api\/(records|team\/records)\/([^/]+)\/participants\/([\w-]+)\/avatar$/);
  if(participant&&request.method==='GET'){
    if(!uuid.test(participant[3]))error(404,'Imagen no disponible.');
    let key;
    if(participant[1]==='records'){
      if(!uuid.test(participant[2]))error(404,'Expediente no encontrado.');
      key=prefix+'records/'+participant[2]+'.json';
    }else{
      if(!context.teamRole)error(403,'Acceso reservado al equipo autorizado.');
      const parts=decodeURIComponent(participant[2]).match(/^([0-9a-f]{64}):([0-9a-f-]{36})$/);
      if(!parts||!uuid.test(parts[2]))error(404,'Expediente no encontrado.');
      key='users/'+parts[1]+'/records/'+parts[2]+'.json';
    }
    const record=(await readJson(bucket,key))?.value,p=record?.participants?.find(p=>p.id===participant[3]);
    if(!p?.profileKey)error(404,'Imagen no disponible.');
    return image(p.profileKey,true);
  }
  if(path!=='/api/profile')return null;
  const key=prefix+'profile.json',existing=await readJson(bucket,key);
  if(request.method==='GET')return json({profile:profileView(existing?.value)});
  if(request.method!=='PUT')error(405,'Método no permitido.');
  const body=JSON.parse(new TextDecoder().decode(await bodyBytes(request,160000)));
  const name=text(body.name,100),headline=text(body.headline,100);
  if(!['person','company'].includes(body.kind)||!name||typeof body.shareInProjects!=='boolean')error(400,'Completa el nombre y el tipo de perfil.');
  const category=text(body.category,60),specialty=text(body.specialty,80);
  if((category&&!allyCategories.includes(category))||!validSpecialty(category,specialty))error(400,'Elige una categoría y una especialidad técnica válida.');
  let professional;try{professional=normalizeProfessional(body,category,specialty,existing?.value||{});}catch(e){error(400,e.message);}
  if(body.revision!==(existing?.value.revision||0))error(409,'El perfil cambió. Recarga antes de guardar.');
  let avatarKey=existing?.value.avatarKey||null,newKey=null;
  if(body.avatar===null)avatarKey=null;
  else if(body.avatar!==undefined){
    let bytes;try{bytes=decodeAvatar(body.avatar);}catch(e){error(400,e.message);}
    newKey=prefix+'profile-images/'+crypto.randomUUID()+'.png';
    await bucket.put(newKey,bytes,{httpMetadata:{contentType:'image/png'}});avatarKey=newKey;
  }
  const profile={...professional,id:existing?.value.id||crypto.randomUUID(),kind:body.kind,name,headline,category,specialty,shareInProjects:body.shareInProjects,avatarKey,revision:(existing?.value.revision||0)+1,updatedAt:new Date().toISOString()};
  try{
    const result=await bucket.put(key,JSON.stringify(profile),{...metadata,onlyIf:existing?{etagMatches:existing.etag}:{etagDoesNotMatch:'*'}});
    if(result===null)error(409,'Otra sesión actualizó el perfil. Recarga para ver los cambios.');
  }catch(e){if(newKey)await bucket.delete(newKey);throw e;}
  if(existing?.value.avatarKey&&existing.value.avatarKey!==avatarKey)await bucket.delete(existing.value.avatarKey).catch(()=>{});
  const indexKey='ally-profiles/'+profile.id+'.json';
  if(profile.shareWithTeam)await bucket.put(indexKey,JSON.stringify({profileKey:key}),metadata);else await bucket.delete(indexKey);
  return json({profile:profileView(profile)});
}
